"""STUB ML implementation — used ONLY when `ml.api` cannot be imported (development).

- Data comes from backend/fixtures/loans.json (generated by backend/fixtures/make_fixtures.py).
  No hand-written answers in code.
- Every response that carries a model version says "stub"; /api/health reports ml_mode="stub"
  and the frontend shows a visible STUB banner.
- No evidence fusion in the stub: base_color == color, escalations == [], priority = colour rank + risk
  (same formula as ml, so the queue order logic is the same).
- check_photo does only what it can honestly compute without a model:
  exact-byte duplicate search inside the caller's sandbox, a coarse Uzbekistan bounding-box
  geo check and a client-vs-server clock check. asset_match is None (no classifier),
  faces are NOT detected/blurred, so no image is returned for storage.
"""
from __future__ import annotations

import hashlib
import json
import threading
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional

MODEL_VERSION = "stub"
FIXTURES_PATH = Path(__file__).resolve().parents[1] / "fixtures" / "loans.json"

UZ_BBOX = (37.1, 45.6, 55.9, 73.2)  # lat_min, lat_max, lon_min, lon_max (coarse)
MAX_CLOCK_SKEW_S = 15 * 60

_loans: Optional[dict] = None
_lock = threading.Lock()
_photo_index: dict = {}  # sandbox_id -> list[(loan_id, sha256)]
COLOR_RANK = {"green": 0, "yellow": 1, "red": 2}


def _fusion_fields(it: dict) -> dict:
    return {"base_color": it["color"], "priority": COLOR_RANK[it["color"]] + it["risk"], "escalations": []}


def _data() -> dict:
    global _loans
    if _loans is None:
        raw = json.loads(FIXTURES_PATH.read_text(encoding="utf-8"))
        _loans = {item["loan"]["loan_id"]: item for item in raw["loans"]}
    return _loans


def _item(loan_id: str) -> dict:
    try:
        return _data()[loan_id]
    except KeyError:
        raise KeyError(loan_id) from None


def get_queue(sandbox_id: Optional[str] = None) -> list:
    items = []
    for it in _data().values():
        loan = it["loan"]
        items.append({
            "loan_id": loan["loan_id"],
            "borrower_name_masked": loan["borrower_name_masked"],
            "purpose": loan["purpose"],
            "amount_uzs": loan["amount_uzs"],
            "region": loan["region"],
            "risk": it["risk"],
            "color": it["color"],
            "top_reason": it["reasons"][0]["text_uz"],
            **_fusion_fields(it),
        })
    return sorted(items, key=lambda x: -x["priority"])


def get_loan(loan_id: str, sandbox_id: Optional[str] = None) -> dict:
    it = _item(loan_id)
    return {**it, **_fusion_fields(it), "model_version": MODEL_VERSION}


def score_loan(loan_id: str) -> dict:
    t = time.perf_counter()
    it = _item(loan_id)
    return {
        "risk": it["risk"],
        "color": it["color"],
        "reasons": it["reasons"],
        "model_version": MODEL_VERSION,
        "latency_ms": round((time.perf_counter() - t) * 1000, 3),
    }


def check_photo(loan_id: str, image_bytes: bytes, lat=None, lon=None, captured_at=None,
                sandbox_id: Optional[str] = None) -> dict:
    t = time.perf_counter()
    _item(loan_id)
    digest = hashlib.sha256(image_bytes).hexdigest()
    key = sandbox_id or "_global"
    with _lock:
        seen = _photo_index.setdefault(key, [])
        dups = sorted({lid for lid, h in seen if h == digest and lid != loan_id})
        seen.append((loan_id, digest))

    geo_ok = None
    if lat is not None and lon is not None:
        geo_ok = UZ_BBOX[0] <= lat <= UZ_BBOX[1] and UZ_BBOX[2] <= lon <= UZ_BBOX[3]
    time_ok = None
    if captured_at is not None:
        client = captured_at if captured_at.tzinfo else captured_at.replace(tzinfo=timezone.utc)
        time_ok = abs((datetime.now(timezone.utc) - client).total_seconds()) <= MAX_CLOCK_SKEW_S

    return {
        "asset_match": None,
        "duplicate_of": [{"loan_id": lid, "similarity": 1.0} for lid in dups],
        "geo_ok": geo_ok,
        "time_ok": time_ok,
        "faces_blurred": False,
        "faces_count": 0,
        "latency_ms": round((time.perf_counter() - t) * 1000, 3),
    }


def reset_sandbox(sandbox_id: Optional[str] = None) -> None:
    """Forget photos of one sandbox; None = all sandboxes."""
    with _lock:
        if sandbox_id is None:
            _photo_index.clear()
        else:
            _photo_index.pop(sandbox_id, None)
